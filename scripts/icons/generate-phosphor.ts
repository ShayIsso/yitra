import { mkdirSync, readFileSync, rmSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { pathToFileURL } from "url";
import { execFileSync } from "child_process";
import { createRequire } from "module";
import { isValidElement, type ReactElement, type ReactNode } from "react";
import type { IconWeight } from "@phosphor-icons/react/dist/lib/types";
import { PHOSPHOR_MANIFEST } from "./phosphor-manifest";

/**
 * Writes src/components/icons/generated/<Icon>.ts for every manifest entry and
 * the src/components/icons/phosphor.generated.ts barrel over them.
 *
 * Phosphor's per-icon modules each carry all six weights (~0.65 kB gz per
 * icon), which puts the redesign's icon set at roughly three times the icon
 * budget. This copies only the manifest's weights out of the package's own
 * icon definitions, so a glyph costs only what it draws (ADR-0015 "Icons").
 */

const ICONS_DIR = "src/components/icons";
const BARREL = join(ICONS_DIR, "phosphor.generated.ts");
const GLYPHS_DIR = join(ICONS_DIR, "generated");
const require = createRequire(import.meta.url);
const pkgJson = require.resolve("@phosphor-icons/react/package.json");
const pkgVersion: string = require(pkgJson).version;
const defsDir = join(dirname(pkgJson), "dist", "defs");
const licenseLines = readFileSync(join(dirname(pkgJson), "LICENSE"), "utf8")
  .trim()
  .split("\n");

type Shape = [tag: string, attrs: Record<string, string>];

function shapesOf(node: ReactNode): Shape[] {
  if (Array.isArray(node)) return node.flatMap(shapesOf);
  if (!isValidElement(node)) return [];
  const { children, ...attrs } = node.props as { children?: ReactNode } & Record<string, unknown>;
  if (typeof node.type !== "string") return shapesOf(children);
  if (children !== undefined) throw new Error(`Nested <${node.type}> is not supported`);
  return [[node.type, Object.fromEntries(Object.entries(attrs).map(([k, v]) => [k, String(v)]))]];
}

function header(): string[] {
  return [
    `// GENERATED by scripts/icons/generate-phosphor.ts from @phosphor-icons/react@${pkgVersion}`,
    "// (https://phosphoricons.com). Do not edit: change the manifest and regenerate.",
  ];
}

/**
 * One module per icon, re-exported by a barrel. Turbopack splits chunks by
 * module, not by export: with every glyph in one module, each route shipped
 * every glyph any route used. Separate modules let a route carry only its own,
 * but only because src/components/icons/package.json declares the directory
 * free of side effects: without it Turbopack keeps every module the barrel
 * re-exports, and the glyphs merge back into one shared chunk.
 */
async function main() {
  rmSync(GLYPHS_DIR, { recursive: true, force: true });
  mkdirSync(GLYPHS_DIR);
  // The icon path data is copied from the package, so its MIT notice travels with it.
  writeFileSync(join(GLYPHS_DIR, "LICENSE"), licenseLines.join("\n") + "\n");

  const barrel = [...header(), ""];
  for (const [name, weights] of Object.entries(PHOSPHOR_MANIFEST)) {
    const defsUrl = pathToFileURL(join(defsDir, `${name}.es.js`)).href;
    const defs: Map<IconWeight, ReactElement> = (await import(defsUrl)).default;
    const data = Object.fromEntries(
      weights.map((w) => {
        const el = defs.get(w);
        if (!el) throw new Error(`${name} has no ${w} weight`);
        return [w, shapesOf(el)];
      }),
    );
    writeFileSync(
      join(GLYPHS_DIR, `${name}.ts`),
      [
        ...header(),
        "// Icon path data from Phosphor Icons, MIT licence: see ./LICENSE.",
        'import { glyph } from "../glyph";',
        "",
        `export const ${name}Icon = /* @__PURE__ */ glyph("${name}", ${JSON.stringify(data)});`,
        "",
      ].join("\n"),
    );
    barrel.push(`export { ${name}Icon } from "./generated/${name}";`);
  }
  writeFileSync(BARREL, barrel.join("\n") + "\n");
  execFileSync("npx", ["prettier", "--write", BARREL, GLYPHS_DIR], { stdio: "inherit" });
}

main().catch((err) => {
  console.error("generate-phosphor failed:", err instanceof Error ? err.message : err);
  process.exit(1);
});
